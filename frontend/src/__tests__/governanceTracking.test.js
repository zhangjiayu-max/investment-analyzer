import { flushPromises } from '@vue/test-utils'
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'

describe('governance tracking', () => {
  beforeEach(() => { vi.resetModules(); vi.useFakeTimers(); Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' }); sessionStorage.clear(); Object.defineProperty(navigator, 'sendBeacon', { configurable: true, value: vi.fn(() => true) }) })
  afterEach(() => { vi.useRealTimers() })
  it('includes per-tab session identity in beacon without referrer content', async () => {
    const tracking = await import('../composables/useTracking')
    tracking.trackPageEnter('quality')
    tracking._flush()
    const blob = navigator.sendBeacon.mock.calls[0][1]
    vi.useRealTimers()
    const raw = await new Promise(resolve => { const reader = new FileReader(); reader.onload = () => resolve(reader.result); reader.readAsText(blob) })
    const body = JSON.parse(raw)
    expect(body.session_id).toMatch(/^s_/)
    expect(body.events[0].session_id).toBe(body.session_id)
    expect(sessionStorage.getItem('ia_session_id')).toBe(body.session_id)
    expect(body.events[0].referrer_page).toBeUndefined()
    tracking.trackPageLeave('quality')
    tracking._flush()
  })
  it('counts only visible time and does not duplicate leave on unmount', async () => {
    const tracking = await import('../composables/useTracking')
    tracking.trackPageEnter('quality')
    vi.advanceTimersByTime(1000)
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' })
    document.dispatchEvent(new Event('visibilitychange'))
    vi.advanceTimersByTime(10000)
    tracking.trackPageLeave('quality')
    tracking._flush()
    vi.useRealTimers()
    const bodies = await Promise.all(navigator.sendBeacon.mock.calls.map(([,blob]) => new Promise(resolve => { const reader = new FileReader(); reader.onload = () => resolve(JSON.parse(reader.result)); reader.readAsText(blob) })))
    const leaves = bodies.flatMap(b => b.events).filter(e => e.action_type === 'page_leave')
    expect(leaves).toHaveLength(1)
    expect(leaves[0].duration_ms).toBe(1000)
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' })
  })
})

it('requeues events after non-success HTTP response', async () => {
  vi.resetModules()
  sessionStorage.clear()
  Object.defineProperty(navigator, 'sendBeacon', { configurable: true, value: vi.fn(() => false) })
  vi.stubGlobal('fetch', vi.fn(async () => ({ok:false,json:async()=>({code:500,message:'failed'})})))
  const tracking = await import('../composables/useTracking')
  tracking.trackFeatureClick('backtest','strategy-backtest')
  tracking._flush()
  await flushPromises()
  expect(JSON.parse(sessionStorage.getItem('ia_track_queue'))[0].feature_key).toBe('backtest')
  vi.unstubAllGlobals()
})

it('accepts wrapped success without requeue and sends bounded batches', async () => {
  vi.resetModules(); sessionStorage.clear()
  sessionStorage.setItem('ia_track_queue',JSON.stringify(Array.from({length:501},()=>({page_key:'quality',action_type:'page_enter',session_id:'s_old'}))))
  Object.defineProperty(navigator,'sendBeacon',{configurable:true,value:vi.fn(()=>false)})
  vi.stubGlobal('fetch',vi.fn(async()=>({ok:true,json:async()=>({code:0,message:'ok',data:{count:50}})})))
  const tracking=await import('../composables/useTracking')
  tracking.trackFeatureClick('test','quality')
  await flushPromises()
  tracking._flush(); await flushPromises()
  const batches=fetch.mock.calls.map(([,options])=>JSON.parse(options.body).events.length)
  expect(Math.max(...batches)).toBeLessThanOrEqual(50)
  expect(JSON.parse(sessionStorage.getItem('ia_track_queue'))).toHaveLength(0)
  vi.unstubAllGlobals()
})
