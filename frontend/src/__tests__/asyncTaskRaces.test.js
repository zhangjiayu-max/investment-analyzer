import { afterEach, beforeEach, expect, it, vi } from 'vitest'
const { listAsyncTasks, getAsyncTaskStatus } = vi.hoisted(() => ({ listAsyncTasks: vi.fn(), getAsyncTaskStatus: vi.fn() }))
vi.mock('../api', () => ({ listAsyncTasks, getAsyncTaskStatus }))
const deferred = () => { let resolve; const promise = new Promise(r => { resolve = r }); return { promise, resolve } }
beforeEach(() => { vi.resetModules(); vi.useFakeTimers(); vi.clearAllMocks() })
afterEach(() => { vi.useRealTimers() })
it('never overlaps slow polls and ignores a completion arriving after reset', async () => {
  const { useAsyncTask } = await import('../composables/useAsyncTask')
  const pending = deferred(); getAsyncTaskStatus.mockReturnValue(pending.promise)
  const task = useAsyncTask('slow'); const complete = vi.fn()
  await task.start(async () => ({ data: { task_id: 1 } }), { onComplete: complete })
  await vi.advanceTimersByTimeAsync(12000)
  expect(getAsyncTaskStatus).toHaveBeenCalledTimes(1)
  task.reset(); pending.resolve({ data: { status: 'done', result: 'old' } })
  await Promise.resolve(); await Promise.resolve()
  expect(task.taskState.value).toBe('idle'); expect(complete).not.toHaveBeenCalled()
})
it('ignores a submission returning after a newer task starts', async () => {
  const { useAsyncTask } = await import('../composables/useAsyncTask')
  const pending = deferred(); const task = useAsyncTask('replace')
  const first = task.start(() => pending.promise)
  await task.start(async () => ({ data: { task_id: 2 } }))
  pending.resolve({ data: { task_id: 1 } }); await first
  expect(task.taskId.value).toBe(2); task.reset()
})
it('retains running credentials through temporary network failures and eventually completes once', async () => {
  const { useAsyncTask } = await import('../composables/useAsyncTask')
  getAsyncTaskStatus.mockRejectedValueOnce(new Error('offline')).mockResolvedValue({ data: { status: 'done', result: { ok: true } } })
  const task = useAsyncTask('network'); const complete = vi.fn()
  await task.start(async () => ({ data: { task_id: 8 } }), { onComplete: complete })
  await vi.advanceTimersByTimeAsync(3000)
  expect(task.taskState.value).toBe('running'); expect(task.taskId.value).toBe(8)
  await vi.advanceTimersByTimeAsync(6000)
  expect(task.taskState.value).toBe('done'); expect(complete).toHaveBeenCalledTimes(1)
})
it('hydrates a server terminal result into the current consumer', async () => {
  const { useAsyncTask } = await import('../composables/useAsyncTask')
  listAsyncTasks.mockResolvedValueOnce({ data: { tasks: [] } }).mockResolvedValueOnce({ data: { tasks: [{ id: 5, status: 'done', result: { news: ['ready'] } }] } })
  const task = useAsyncTask('hydrate'); const complete = vi.fn()
  await task.restoreFromServer({ onComplete: complete })
  expect(complete).toHaveBeenCalledWith({ news: ['ready'] })
})
it('ignores server restore responses after reset and retains old local IDs when offline', async () => {
  const { useAsyncTask } = await import('../composables/useAsyncTask')
  const { useTaskStore } = await import('../composables/useTaskStore')
  const task = useAsyncTask('restore-race'); const pending = deferred()
  listAsyncTasks.mockReturnValueOnce(pending.promise)
  const restore = task.restoreFromServer(); task.reset()
  pending.resolve({ data: { tasks: [{ id: 6, status: 'running' }] } }); await restore
  expect(task.taskState.value).toBe('idle')
  useTaskStore().setTask('restore-race', { taskId: 17, state: 'running', updatedAt: 1 })
  listAsyncTasks.mockRejectedValue(new Error('offline'))
  await task.restoreFromServer()
  expect(task.taskState.value).toBe('running'); expect(task.taskId.value).toBe(17)
  task.reset()
})
